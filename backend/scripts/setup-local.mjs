import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const backendDir = path.resolve(__dirname, "..");
const repoRoot = path.resolve(backendDir, "..");
const dashboardDir = path.resolve(repoRoot, "dashboard");
const wranglerBin = path.join(
  backendDir,
  "node_modules",
  "wrangler",
  "bin",
  "wrangler.js",
);

const wranglerEnv = {
  ...process.env,
  XDG_CONFIG_HOME: path.join(repoRoot, ".wrangler-config"),
  WRANGLER_SEND_METRICS: "false",
};

function runWrangler(args) {
  if (fs.existsSync(wranglerBin)) {
    execFileSync(process.execPath, [wranglerBin, ...args], {
      cwd: backendDir,
      env: wranglerEnv,
      stdio: "inherit",
    });
    return;
  }
  execFileSync("npx", ["wrangler", ...args], {
    cwd: backendDir,
    env: wranglerEnv,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
}

function sqlText(value) {
  if (value === null || value === undefined) {
    return "NULL";
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

function createScopedKey(spec) {
  const keyId = `k_${crypto.randomBytes(8).toString("hex")}`;
  const secret = crypto.randomBytes(24).toString("base64url");
  const token = `etk_${keyId}.${secret}`;
  const secretHash = `sha256:${crypto.createHash("sha256").update(secret).digest("hex")}`;
  return {
    ...spec,
    keyId,
    token,
    secretHash,
  };
}

function main() {
  console.log("Applying local D1 migrations...");
  runWrangler([
    "d1",
    "migrations",
    "apply",
    "expense-tracker-local",
    "--local",
    "-y",
    "--config",
    "wrangler.integration.jsonc",
    "--persist-to",
    "../.wrangler/state",
  ]);

  const now = new Date().toISOString().replace(/\.\d{3}Z$/, "Z");
  const keys = [
    createScopedKey({
      clientId: "client_local_viewer",
      name: "Local Web Viewer",
      kind: "local_viewer",
      scopes: ["transactions:read"],
    }),
    createScopedKey({
      clientId: "client_agent_dev",
      name: "Development Agent",
      kind: "agent",
      scopes: ["transactions:read", "transactions:create", "transactions:parse"],
    }),
    createScopedKey({
      clientId: "client_telegram_dev",
      name: "Development Telegram Bot",
      kind: "telegram",
      scopes: ["transactions:create", "transactions:parse"],
    }),
  ];

  const statements = [];
  for (const item of keys) {
    statements.push(
      `INSERT INTO api_clients (id, name, kind) VALUES (${sqlText(item.clientId)}, ${sqlText(item.name)}, ${sqlText(item.kind)}) ON CONFLICT(id) DO UPDATE SET name = excluded.name, kind = excluded.kind;`,
    );
  }
  const clientList = keys.map((k) => sqlText(k.clientId)).join(", ");
  statements.push(
    `UPDATE api_keys SET revoked_at = ${sqlText(now)} WHERE client_id IN (${clientList}) AND revoked_at IS NULL;`,
  );
  for (const item of keys) {
    statements.push(
      `INSERT INTO api_keys (id, client_id, secret_hash, scopes_json, created_at, expires_at, revoked_at) VALUES (${sqlText(item.keyId)}, ${sqlText(item.clientId)}, ${sqlText(item.secretHash)}, ${sqlText(JSON.stringify(item.scopes))}, ${sqlText(now)}, NULL, NULL);`,
    );
  }

  const tempSqlPath = path.join(backendDir, ".tmp-setup-local.sql");
  fs.writeFileSync(tempSqlPath, `${statements.join("\n")}\n`, "utf8");

  try {
    console.log("Provisioning scoped local API clients and keys...");
    runWrangler([
      "d1",
      "execute",
      "expense-tracker-local",
      "--local",
      "--config",
      "wrangler.integration.jsonc",
      "--persist-to",
      "../.wrangler/state",
      "--file",
      tempSqlPath,
    ]);
  } finally {
    if (fs.existsSync(tempSqlPath)) {
      fs.unlinkSync(tempSqlPath);
    }
  }

  const localViewer = keys.find((k) => k.kind === "local_viewer");
  const ownerEmail = "owner@example.com";

  const backendDevVarsPath = path.join(backendDir, ".dev.vars");
  fs.writeFileSync(
    backendDevVarsPath,
    [
      "# Generated by cd backend && npm run db:setup:local — local development only",
      "DEV_AUTH_MODE=local",
      `OWNER_EMAIL=${ownerEmail}`,
      "",
    ].join("\n"),
    "utf8",
  );

  const envLocalPath = path.join(dashboardDir, ".env.local");
  const envContent = [
    "# Generated by cd backend && npm run db:setup:local — keep private on this machine",
    "EXPENSE_TRACKER_API_URL=http://127.0.0.1:8787",
    `EXPENSE_TRACKER_READ_KEY=${localViewer.token}`,
    "EXPENSE_TRACKER_MODE=owner",
    "EXPENSE_TRACKER_DASHBOARD_API_URL=http://127.0.0.1:8788",
    `EXPENSE_TRACKER_OWNER_EMAIL=${ownerEmail}`,
    "",
  ].join("\n");
  fs.writeFileSync(envLocalPath, envContent, "utf8");

  console.log("\nLocal D1 database and development credentials are ready.");
  console.log(`Wrote local owner dev vars to ${path.relative(repoRoot, backendDevVarsPath)}`);
  console.log(`Wrote local dashboard config to ${path.relative(repoRoot, envLocalPath)}`);
  console.log("\nGenerated development keys (shown once):");
  for (const item of keys) {
    console.log(
      `  - ${item.kind.padEnd(12)} (${item.scopes.join(", ")}): ${item.token}`,
    );
  }
}

main();
